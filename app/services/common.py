"""Helpers shared by the service modules: ids, the clock and the If-Match check."""

from __future__ import annotations

from datetime import UTC, datetime
from uuid import uuid4

from sqlalchemy import Column, Connection, func, select

from app.errors import Conflict


def utcnow() -> datetime:
    """Current time as a naive UTC datetime, the form stored in every timestamp column."""
    return datetime.now(UTC).replace(tzinfo=None)


def next_id(conn: Connection, column: Column[int]) -> int:
    """Next value of an application-assigned integer sequence: MAX(column) + 1.

    Safe only inside a write transaction. On SQLite that transaction holds the
    database write lock from BEGIN IMMEDIATE, so two writers can never read the same
    maximum. On PostgreSQL two transactions could, and the UNIQUE constraint would
    fail one of them; an identity column is the right tool there.
    """
    return conn.execute(select(func.coalesce(func.max(column), 0) + 1)).scalar_one()


def new_id(prefix: str) -> str:
    """Opaque synthetic id such as ord_3f9c... Generated by the service, never by clients."""
    return f"{prefix}_{uuid4().hex[:16]}"


def check_expected_version(current: int, expected: int | None, subject: str) -> None:
    """Optimistic concurrency: fail if the client's If-Match version is stale."""
    if expected is not None and expected != current:
        raise Conflict("version_conflict", f"{subject} is at version {current}, but If-Match said {expected}")
